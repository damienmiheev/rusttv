/// The About page's update line for a status, in the current language
/// (`Strings.update-line` in home.slint); says what OK does when it isn't a
/// plain check.
fn update_line(window: &HomeWindow, status: &UpdateStatus) -> SharedString {
    let (kind, detail) = match status {
        UpdateStatus::Idle => (0, String::new()),
        UpdateStatus::Checking => (1, String::new()),
        UpdateStatus::UpToDate => (2, String::new()),
        UpdateStatus::Available(version) => (3, version.clone()),
        UpdateStatus::NeedsPermission(version) => (4, version.clone()),
        UpdateStatus::Downloading(percent) => (5, percent.to_string()),
        UpdateStatus::Installing => (6, String::new()),
        UpdateStatus::Installed => (7, String::new()),
        UpdateStatus::Failed(reason) => (8, reason.clone()),
    };
    window
        .global::<Strings>()
        .invoke_update_line(kind, detail.into())
}

/// Maps Slint key text to a model input.
///
/// Arrows are U+F700–F703, OK arrives as Return, and Android's BACK as U+F748
/// (RESEARCH.md §8). Escape and Backspace act as Back on the desktop.
fn input_for_key(text: &str, pressed: bool) -> Option<Input> {
    let input = match (text, pressed) {
        ("\n" | "\r", true) => Input::OkPressed,
        ("\n" | "\r", false) => Input::OkReleased,
        (_, false) => return None,
        ("\u{F700}", true) => Input::Up,
        ("\u{F701}", true) => Input::Down,
        ("\u{F702}", true) => Input::Left,
        ("\u{F703}", true) => Input::Right,
        ("\u{F748}" | "\u{1b}" | "\u{8}", true) => Input::Back,
        _ => return None,
    };
    Some(input)
}

/// The hero glow for artwork, from its small copy (see [`GLOW_SOURCE_SIZE`]).
fn hero_glow(source: &Bitmap) -> generated::Glow {
    let glow = source.glow(BACKDROP_BASE_TONE, BACKDROP_GLOW_TONE);
    let colour = |[red, green, blue]: [u8; 3]| slint::Color::from_rgb_u8(red, green, blue);
    generated::Glow {
        base: colour(glow.base),
        color: colour(glow.colour),
        x: glow.x,
        y: glow.y,
        strength: glow.strength,
    }
}

fn image(bitmap: &Bitmap) -> slint::Image {
    slint::Image::from_rgba8(SharedPixelBuffer::clone_from_slice(
        bitmap.rgba(),
        bitmap.width(),
        bitmap.height(),
    ))
}

