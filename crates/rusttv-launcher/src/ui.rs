/// Idle time before the focused tile starts to sway (it fades in, so this can
/// be short); quick D-pad scrolling passes tiles without starting a sway.
const SWAY_AFTER: Duration = Duration::from_millis(300);

/// Idle time after which the sway eases back to rest (owner's choice).
///
/// While a tile sways, Skia redraws the whole screen every frame: about 44% of
/// one core on the Philips 65OLED818. Stopping keeps an idle home screen at ~0%.
const SWAY_UNTIL: Duration = Duration::from_secs(20);

/// Artwork listed as [`Artwork::Later`] loads this many apps per timer tick,
/// after the first frame. About 7 ms per app on the Philips TV, so a tick
/// stays short and keys stay responsive while banners arrive.
const ARTWORK_PER_TICK: usize = 2;

/// Interval between artwork loading ticks.
const ARTWORK_TICK: Duration = Duration::from_millis(16);

/// How long focus must rest before the hero follows it.
const HERO_DELAY: Duration = Duration::from_millis(150);

/// How long the "couldn't open" message stays.
const TOAST_TIME: Duration = Duration::from_secs(3);

/// Size of the small copy of each banner kept to compute its hero glow.
const GLOW_SOURCE_SIZE: (u32, u32) = (48, 27);

/// HCT tone of the backdrop base: near black, like Material's dark surfaces.
const BACKDROP_BASE_TONE: f64 = 12.0;

/// HCT tone of the colour glow: Material's dark-theme "primary container"
/// tone, colourful but dark enough for the white title.
const BACKDROP_GLOW_TONE: f64 = 30.0;

/// Lines of the notices passed to the window at a time: more than fit, the
/// rest is clipped (long lines wrap). Only a slice is laid out, never all
/// ~10,000 lines.
const NOTICES_SENT_LINES: usize = 40;

/// About how many lines the notices panel shows at once; scrolling stops when
/// the last ones are in view.
const NOTICES_SCREEN_LINES: usize = 32;

/// Lines one Up or Down press scrolls the notices; a held key repeats it.
const NOTICES_STEP: usize = 5;

/// Settings for [`run`].
#[derive(Debug, Clone, Default)]
pub struct RunOptions {
    /// Mirror left and right for right-to-left languages.
    pub right_to_left: bool,
    /// Pretend the launched app took over the screen this long after a launch.
    ///
    /// For the desktop dev mode, where nothing pauses the launcher. On a TV,
    /// leave it `None`: the activity lifecycle reports the pause.
    pub simulated_pause: Option<Duration>,
    /// Where the tile order is kept; `None` starts
    /// alphabetical every time and saves nothing.
    pub order_file: Option<PathBuf>,
    /// Lets the platform report that the launcher left or came back to the screen.
    pub lifecycle: Lifecycle,
}

/// Reports activity lifecycle events to a running home screen.
///
/// Create one, pass a clone in [`RunOptions`], and call it from the platform's
/// event handler on the UI thread. Calls before [`run`] starts are ignored.
#[derive(Clone, Default)]
pub struct Lifecycle(Rc<RefCell<Weak<RefCell<Controller>>>>);

impl Lifecycle {
    /// The launcher left the screen: an app opened or the screen turned off.
    pub fn paused(&self) {
        self.deliver(|controller| controller.input(Input::Paused));
    }

    /// The launcher is on screen again; re-reads the app list if it changed.
    pub fn resumed(&self) {
        self.deliver(Controller::resume);
    }

    /// Runs `event` on the controller from a fresh timer callback, so it never
    /// meets a controller that is already borrowed.
    fn deliver(&self, event: impl FnOnce(&mut Controller) + 'static) {
        let me = self.0.borrow().clone();
        Timer::single_shot(Duration::ZERO, move || {
            if let Some(controller) = me.upgrade() {
                event(&mut controller.borrow_mut());
            }
        });
    }
}

impl std::fmt::Debug for Lifecycle {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let running = self.0.borrow().strong_count() > 0;
        f.debug_struct("Lifecycle")
            .field("running", &running)
            .finish()
    }
}

/// Shows the home screen and runs the UI event loop until the window closes.
pub fn run(platform: impl Platform + 'static, options: RunOptions) -> Result<(), PlatformError> {
    let (window, _controller) = start(platform, options, real_clock())?;
    window.run().map_err(ui_error)
}

/// One step of a scripted [`run_demo`].
#[cfg(any(test, feature = "test-util"))]
#[derive(Debug, Clone, Copy)]
pub enum DemoStep {
    /// Press and release a key, given as Slint key text (see `input_for_key`).
    Tap(&'static str),
    /// Press a key without releasing it.
    Press(&'static str),
    /// Release a pressed key.
    Release(&'static str),
    /// Let time pass, e.g. for animations or timers.
    Wait(Duration),
    /// Render the window and pass the picture to the callback under this name.
    Snapshot(&'static str),
}

/// Runs the home screen through scripted key presses, taking snapshots, then quits.
///
/// For checking the UI without a TV or screen-capture permission. Snapshot
/// failures are passed to the callback as errors.
#[cfg(any(test, feature = "test-util"))]
pub fn run_demo(
    platform: impl Platform + 'static,
    options: RunOptions,
    steps: &[DemoStep],
    on_snapshot: impl FnMut(&str, Result<Bitmap, PlatformError>) + 'static,
) -> Result<(), PlatformError> {
    let (window, _controller) = start(platform, options, real_clock())?;
    let demo = Rc::new(Demo {
        steps: steps.to_vec(),
        window: window.as_weak(),
        on_snapshot: RefCell::new(Box::new(on_snapshot)),
    });
    Timer::single_shot(Duration::ZERO, move || demo.step(0));
    window.run().map_err(ui_error)
}

#[cfg(any(test, feature = "test-util"))]
type SnapshotCallback = Box<dyn FnMut(&str, Result<Bitmap, PlatformError>)>;

/// State of a running [`run_demo`].
#[cfg(any(test, feature = "test-util"))]
struct Demo {
    steps: Vec<DemoStep>,
    window: slint::Weak<HomeWindow>,
    on_snapshot: RefCell<SnapshotCallback>,
}

#[cfg(any(test, feature = "test-util"))]
impl Demo {
    /// Gap after each key event, so one event is handled before the next.
    const KEY_GAP: Duration = Duration::from_millis(50);

    /// Runs step `index`, then schedules the next one relative to now, so slow
    /// steps (snapshots) do not eat into the following waits.
    fn step(self: Rc<Self>, index: usize) {
        use slint::platform::WindowEvent;

        let Some(window) = self.window.upgrade() else {
            return;
        };
        let Some(step) = self.steps.get(index).copied() else {
            // Fails only when no event loop runs, and then there is nothing to quit.
            let _ = slint::quit_event_loop();
            return;
        };
        let key = |text: &str, pressed: bool| {
            let text = text.into();
            window.window().dispatch_event(if pressed {
                WindowEvent::KeyPressed { text }
            } else {
                WindowEvent::KeyReleased { text }
            });
        };
        let mut delay = Self::KEY_GAP;
        match step {
            DemoStep::Tap(text) => {
                key(text, true);
                key(text, false);
            }
            DemoStep::Press(text) => key(text, true),
            DemoStep::Release(text) => key(text, false),
            DemoStep::Wait(duration) => delay = duration,
            DemoStep::Snapshot(name) => {
                let picture =
                    window
                        .window()
                        .take_snapshot()
                        .map_err(ui_error)
                        .and_then(|buffer| {
                            Bitmap::new(buffer.width(), buffer.height(), buffer.as_bytes().to_vec())
                                .ok_or_else(|| {
                                    PlatformError::call("snapshot", "unexpected buffer size")
                                })
                        });
                (self.on_snapshot.borrow_mut())(name, picture);
            }
        }
        Timer::single_shot(delay, move || self.step(index + 1));
    }
}

/// Creates the window and its controller; the caller runs the event loop.
fn start(
    platform: impl Platform + 'static,
    options: RunOptions,
    clock: Clock,
) -> Result<(HomeWindow, Rc<RefCell<Controller>>), PlatformError> {
    let window = HomeWindow::new().map_err(ui_error)?;
    let controller = Controller::new(Box::new(platform), &window, options, clock);

    let weak = Rc::downgrade(&controller);
    window.on_key(move |text, pressed, repeat| {
        weak.upgrade()
            .is_some_and(|controller| controller.borrow_mut().key(&text, pressed, repeat))
    });
    Ok((window, controller))
}

/// Time since the home screen started; passed in so tests can use Slint's mocked time.
type Clock = Box<dyn Fn() -> Duration>;

fn real_clock() -> Clock {
    let started = Instant::now();
    Box::new(move || started.elapsed())
}

fn ui_error(error: impl std::fmt::Display) -> PlatformError {
    PlatformError::call("ui", error.to_string())
}

struct Controller {
    home: Home,
    platform: Box<dyn Platform>,
    options: RunOptions,
    /// What the window shows of each app, by app id.
    apps: HashMap<String, AppView>,
    /// Hero glows per app id, computed on first focus.
    glows: HashMap<String, generated::Glow>,
    /// Tiles currently in the window's model, to rebuild it only when they change.
    shown: Vec<TileId>,
    tiles: Rc<VecModel<TileData>>,
    hero: Option<TileId>,
    hero_a_front: bool,
    pressed: bool,
    clock: Clock,
    window: slint::Weak<HomeWindow>,
    me: Weak<RefCell<Controller>>,
    tick_timer: Timer,
    idle_timer: Timer,
    hero_timer: Timer,
    toast_timer: Timer,
    pause_timer: Timer,
    /// Apps whose artwork is still [`Artwork::Later`], in tile order.
    pending_artwork: VecDeque<String>,
    artwork_timer: Timer,
    /// The licence notices while the About page is open; read when it opens.
    notices: Option<Notices>,
}

impl Controller {
    fn new(
        platform: Box<dyn Platform>,
        window: &HomeWindow,
        options: RunOptions,
        clock: Clock,
    ) -> Rc<RefCell<Self>> {
        let tiles = Rc::new(VecModel::default());
        window.set_tiles(ModelRc::from(tiles.clone()));
        window.set_version(env!("CARGO_PKG_VERSION").into());

        let order = options
            .order_file
            .as_deref()
            .map_or_else(Order::default, |path| {
                let loaded = order_file::load(path);
                if let Some(warning) = loaded.warning {
                    log::warn!("{warning}");
                }
                loaded.order
            });
        let controller = Rc::new_cyclic(|me| {
            RefCell::new(Self {
                home: Home::new(order, options.right_to_left),
                platform,
                options,
                apps: HashMap::new(),
                glows: HashMap::new(),
                shown: Vec::new(),
                tiles,
                hero: None,
                hero_a_front: true,
                pressed: false,
                clock,
                window: window.as_weak(),
                me: me.clone(),
                tick_timer: Timer::default(),
                idle_timer: Timer::default(),
                hero_timer: Timer::default(),
                toast_timer: Timer::default(),
                pause_timer: Timer::default(),
                pending_artwork: VecDeque::new(),
                artwork_timer: Timer::default(),
                notices: None,
            })
        });
        *controller.borrow().options.lifecycle.0.borrow_mut() = Rc::downgrade(&controller);
        {
            let mut this = controller.borrow_mut();
            this.reload_apps();
            this.restart_idle();
            // `render` schedules the hero after HERO_DELAY, so the first frame
            // does not wait for its backdrop; it fades in like any focus change.
            this.render();
        }
        controller
    }

    /// Re-reads the app list when the platform reports a change. A failed check
    /// counts as a change, so the list is never left stale.
    fn resume(&mut self) {
        let changed = self.platform.take_apps_changed().unwrap_or_else(|error| {
            log::warn!("checking for app changes failed: {error}");
            true
        });
        if changed {
            log::info!("app list changed; reloading");
            self.reload_apps();
            // Rebuild tiles and hero too: an updated app may have a new banner.
            self.shown.clear();
            self.hero = None;
            self.render();
        }
    }

    /// Re-reads the app list from the platform.
    fn reload_apps(&mut self) {
        match self.platform.list_apps() {
            Ok(entries) => {
                let apps: Vec<App> = entries.iter().map(|entry| entry.app.clone()).collect();
                self.glows.clear();
                self.apps = entries
                    .into_iter()
                    .map(|entry| (entry.app.id.clone(), AppView::new(entry)))
                    .collect();
                if self.home.set_apps(&apps) {
                    self.save_order();
                }
                self.pending_artwork = self
                    .home
                    .tiles()
                    .iter()
                    .filter_map(|tile| match tile {
                        TileId::App(id) if self.apps.get(id).is_some_and(AppView::is_pending) => {
                            Some(id.clone())
                        }
                        _ => None,
                    })
                    .collect();
                self.load_artwork_later();
            }
            Err(error) => {
                self.home.set_apps(&[]);
                self.show_toast(format!("Couldn't load apps: {error}"));
            }
        }
    }

    /// Starts loading pending artwork on a timer, so the first frame (and each
    /// key) never waits for every banner.
    fn load_artwork_later(&mut self) {
        if self.pending_artwork.is_empty() {
            self.artwork_timer.stop();
            return;
        }
        let me = self.me.clone();
        self.artwork_timer
            .start(TimerMode::Repeated, ARTWORK_TICK, move || {
                if let Some(controller) = me.upgrade() {
                    controller.borrow_mut().load_some_artwork();
                }
            });
    }

    /// Loads the next few pending artworks and shows them.
    fn load_some_artwork(&mut self) {
        for _ in 0..ARTWORK_PER_TICK {
            let Some(id) = self.pending_artwork.pop_front() else {
                break;
            };
            let artwork = self.platform.artwork(&id).unwrap_or_else(|error| {
                log::warn!("loading the artwork of {id} failed: {error}");
                Artwork::Missing
            });
            let Some(app) = self.apps.get_mut(&id) else {
                continue;
            };
            app.set_artwork(&artwork);
            let tile = TileId::App(id);
            if let Some(index) = self.shown.iter().position(|shown| *shown == tile) {
                self.tiles.set_row_data(index, self.tile_data(&tile));
            }
            if self.hero.as_ref() == Some(&tile) {
                // Redraw the hero with the picture (it fades in like a tile).
                self.hero = None;
                self.show_hero();
            }
        }
        if self.pending_artwork.is_empty() {
            self.artwork_timer.stop();
        }
    }

    /// Handles a key from the window; returns whether it was used.
    ///
    /// A held OK repeats its key-down about every 50 ms. Those repeats are
    /// swallowed here: passed on, each restarted the long-press timer, so move
    /// mode only began on release. Held arrows keep repeating, to scroll.
    fn key(&mut self, text: &str, pressed: bool, repeat: bool) -> bool {
        let Some(input) = input_for_key(text, pressed) else {
            return false;
        };
        if !(repeat && input == Input::OkPressed) {
            self.input(input);
        }
        true
    }

    fn input(&mut self, input: Input) {
        let effect = self.home.handle(input, (self.clock)());
        if input != Input::Tick {
            self.pressed = input == Input::OkPressed && self.home.state() == State::Browse;
            self.restart_idle();
        }
        match effect {
            Some(Effect::Launch(id)) => self.launch(&id),
            Some(Effect::ShowLaunchError(id)) => {
                let label = self.apps.get(&id).map_or(id.as_str(), |app| &app.label);
                self.show_toast(format!("Couldn't open {label}"));
            }
            Some(Effect::SaveOrder) => self.save_order(),
            Some(Effect::OpenAbout) => self.open_notices(),
            None => {}
        }
        if let Some(notices) = &mut self.notices {
            match input {
                Input::Up => notices.scroll_up(),
                Input::Down => notices.scroll_down(),
                _ => {}
            }
        }
        self.schedule_tick();
        self.render();
    }

    /// Reads the notices for the About page; a failure is shown in their place.
    fn open_notices(&mut self) {
        let text = self.platform.notices().unwrap_or_else(|error| {
            log::warn!("loading the licence notices failed: {error}");
            format!("Couldn't load the licence notices: {error}")
        });
        self.notices = Some(Notices::new(text));
    }

    /// Writes the order file. A failure only costs the order on the next start,
    /// so it is logged rather than shown.
    fn save_order(&self) {
        if let Some(path) = &self.options.order_file
            && let Err(error) = order_file::save(path, self.home.order())
        {
            log::warn!(
                "saving the tile order to {} failed: {error}",
                path.display()
            );
        }
    }

    fn launch(&mut self, id: &str) {
        match self.platform.launch(id) {
            Ok(()) => {
                if let Some(delay) = self.options.simulated_pause {
                    let me = self.me.clone();
                    self.pause_timer
                        .start(TimerMode::SingleShot, delay, move || {
                            if let Some(controller) = me.upgrade() {
                                controller.borrow_mut().input(Input::Paused);
                            }
                        });
                }
            }
            Err(_) => self.input(Input::LaunchFailed),
        }
    }

    /// Sends a [`Input::Tick`] when the model's next timer can be due.
    fn schedule_tick(&mut self) {
        let delay = match self.home.state() {
            State::Browse if self.pressed => LONG_PRESS,
            State::Launching => LAUNCH_TIMEOUT,
            State::Moving => MOVE_IDLE_TIMEOUT,
            State::Browse | State::About => {
                self.tick_timer.stop();
                return;
            }
        };
        let me = self.me.clone();
        self.tick_timer
            .start(TimerMode::SingleShot, delay, move || {
                if let Some(controller) = me.upgrade() {
                    controller.borrow_mut().input(Input::Tick);
                }
            });
    }

    /// Back to the still focus look, sway from [`SWAY_AFTER`], back to still at
    /// [`SWAY_UNTIL`]. The sway fades in and out (`home.slint`), so neither
    /// change jumps.
    fn restart_idle(&mut self) {
        self.set_idle_phase(0);
        let me = self.me.clone();
        self.idle_timer
            .start(TimerMode::SingleShot, SWAY_AFTER, move || {
                let Some(controller) = me.upgrade() else {
                    return;
                };
                let this = controller.borrow();
                this.set_idle_phase(1);
                let window = this.window.clone();
                this.idle_timer
                    .start(TimerMode::SingleShot, SWAY_UNTIL - SWAY_AFTER, move || {
                        if let Some(window) = window.upgrade() {
                            window.set_idle_phase(0);
                        }
                    });
            });
    }

    fn set_idle_phase(&self, phase: i32) {
        if let Some(window) = self.window.upgrade() {
            window.set_idle_phase(phase);
        }
    }

    fn show_toast(&mut self, text: String) {
        if let Some(window) = self.window.upgrade() {
            window.set_toast(text.into());
        }
        let window = self.window.clone();
        self.toast_timer
            .start(TimerMode::SingleShot, TOAST_TIME, move || {
                if let Some(window) = window.upgrade() {
                    window.set_toast("".into());
                }
            });
    }

    /// Pushes model state to the window. Slint only redraws what actually changed.
    fn render(&mut self) {
        let Some(window) = self.window.upgrade() else {
            return;
        };
        if self.home.tiles() != self.shown {
            self.shown = self.home.tiles().to_vec();
            let rows: Vec<TileData> = self.shown.iter().map(|id| self.tile_data(id)).collect();
            self.tiles.set_vec(rows);
        }
        window.set_focused_index(i32::try_from(self.home.focus()).unwrap_or(i32::MAX));
        match self.home.scroll() {
            Scroll::Shelf => window.set_shelf(true),
            Scroll::Grid { first_row } => {
                window.set_shelf(false);
                window.set_first_row(i32::try_from(first_row).unwrap_or(i32::MAX));
            }
        }
        window.set_mode(mode_value(self.home.state()));
        window.set_pressed(self.pressed);
        if self.home.state() != State::About && self.notices.take().is_some() {
            // Closed: free the text until the page opens again.
            window.set_notices("".into());
        }
        if let Some(notices) = &self.notices {
            window.set_notices(notices.visible().into());
            window.set_notices_position(notices.position());
            window.set_notices_fraction(notices.fraction());
        }

        if self.home.focused() != self.hero.as_ref() {
            let me = self.me.clone();
            self.hero_timer
                .start(TimerMode::SingleShot, HERO_DELAY, move || {
                    if let Some(controller) = me.upgrade() {
                        controller.borrow_mut().show_hero();
                    }
                });
        }
    }

    /// Cross-fades the hero to the focused tile.
    fn show_hero(&mut self) {
        let Some(window) = self.window.upgrade() else {
            return;
        };
        let focused = self.home.focused().cloned();
        if focused == self.hero {
            return;
        }
        let data = focused
            .as_ref()
            .map(|id| self.tile_data(id))
            .unwrap_or_default();
        let glow = match &focused {
            Some(TileId::App(component)) => self.glow(component),
            _ => None,
        }
        .unwrap_or_default();
        // Fill the hidden layer, then make it the front one.
        if self.hero_a_front {
            window.set_hero_b(data);
            window.set_hero_b_glow(glow);
        } else {
            window.set_hero_a(data);
            window.set_hero_a_glow(glow);
        }
        self.hero_a_front = !self.hero_a_front;
        window.set_hero_a_front(self.hero_a_front);
        self.hero = focused;
    }

    /// The hero glow for an app; `None` if it has no artwork.
    fn glow(&mut self, component: &str) -> Option<generated::Glow> {
        if let Some(cached) = self.glows.get(component) {
            return Some(cached.clone());
        }
        let source = self.apps.get(component)?.glow_source.as_ref()?;
        let glow = source.glow(BACKDROP_BASE_TONE, BACKDROP_GLOW_TONE);
        let colour = |[red, green, blue]: [u8; 3]| slint::Color::from_rgb_u8(red, green, blue);
        let glow = generated::Glow {
            base: colour(glow.base),
            color: colour(glow.colour),
            x: glow.x,
            y: glow.y,
            strength: glow.strength,
        };
        self.glows.insert(component.to_owned(), glow.clone());
        Some(glow)
    }

    fn tile_data(&self, id: &TileId) -> TileData {
        let TileId::App(component) = id else {
            return TileData {
                kind: 3,
                ..TileData::default()
            };
        };
        let Some(app) = self.apps.get(component) else {
            return TileData {
                label: component.as_str().into(),
                kind: 2,
                ..TileData::default()
            };
        };
        TileData {
            label: app.label.as_str().into(),
            // A cheap handle: the tile and the hero share one image and texture.
            image: app.image.clone(),
            kind: app.kind,
        }
    }
}

/// What the window shows of one app, made once per app list.
///
/// The artwork's pixels are copied into one Slint image and dropped, so each
/// banner is held once (a tile and the hero share the image), plus a 48×27 copy
/// for the hero glow.
struct AppView {
    label: String,
    image: slint::Image,
    /// The `kind` of `TileData`: 0 banner, 1 icon only, 2 no artwork, 4 loading.
    kind: i32,
    glow_source: Option<Bitmap>,
}

impl AppView {
    fn new(entry: AppEntry) -> Self {
        let mut view = Self {
            label: entry.app.label,
            image: slint::Image::default(),
            kind: 2,
            glow_source: None,
        };
        view.set_artwork(&entry.artwork);
        view
    }

    /// Takes the picture from `artwork`; its pixels are copied, not kept.
    fn set_artwork(&mut self, artwork: &Artwork) {
        let (image, kind, glow_source) = match artwork {
            Artwork::Banner(bitmap) => (image(bitmap), 0, Some(bitmap)),
            Artwork::Icon(bitmap) => (image(bitmap), 1, Some(bitmap)),
            Artwork::Missing => (slint::Image::default(), 2, None),
            Artwork::Later => (slint::Image::default(), 4, None),
        };
        self.image = image;
        self.kind = kind;
        self.glow_source =
            glow_source.map(|bitmap| bitmap.shrink(GLOW_SOURCE_SIZE.0, GLOW_SOURCE_SIZE.1));
    }

    /// Whether the artwork is still to be loaded ([`Artwork::Later`]).
    fn is_pending(&self) -> bool {
        self.kind == 4
    }
}

/// The licence notices and how far they are scrolled.
struct Notices {
    text: String,
    /// Byte offset where each line starts.
    starts: Vec<usize>,
    /// The line at the top of the panel.
    first: usize,
}

impl Notices {
    fn new(text: String) -> Self {
        let starts = std::iter::once(0)
            .chain(text.match_indices('\n').map(|(index, _)| index + 1))
            .collect();
        Self {
            text,
            starts,
            first: 0,
        }
    }

    /// The top line when the last lines are in view.
    fn last_first(&self) -> usize {
        self.starts.len().saturating_sub(NOTICES_SCREEN_LINES)
    }

    fn scroll_up(&mut self) {
        self.first = self.first.saturating_sub(NOTICES_STEP);
    }

    fn scroll_down(&mut self) {
        self.first = (self.first + NOTICES_STEP).min(self.last_first());
    }

    /// The lines from the top of the panel on, [`NOTICES_SENT_LINES`] of them.
    fn visible(&self) -> &str {
        let start = self.starts.get(self.first).copied().unwrap_or(0);
        let end = self
            .starts
            .get(self.first + NOTICES_SENT_LINES)
            .copied()
            .unwrap_or(self.text.len());
        &self.text[start..end]
    }

    /// How far down the panel is scrolled, 0..1.
    fn position(&self) -> f32 {
        match self.last_first() {
            0 => 0.0,
            last => self.first as f32 / last as f32,
        }
    }

    /// The share of all lines the panel shows, 0..1, for the scroll bar.
    fn fraction(&self) -> f32 {
        (NOTICES_SCREEN_LINES as f32 / self.starts.len() as f32).min(1.0)
    }
}

/// The value of the `Mode` global in `home.slint` for a model state.
fn mode_value(state: State) -> i32 {
    match state {
        State::Browse => 0,
        State::Moving => 1,
        State::Launching => 2,
        State::About => 3,
    }
}

/// Maps Slint key text to a model input.
///
/// Arrows are U+F700–F703, OK arrives as Return, and Android's BACK as U+F748
/// (RESEARCH.md §8). Escape and Backspace act as Back on the desktop.
fn input_for_key(text: &str, pressed: bool) -> Option<Input> {
    let input = match (text, pressed) {
        ("\n" | "\r", true) => Input::OkPressed,
        ("\n" | "\r", false) => Input::OkReleased,
        (_, false) => return None,
        ("\u{F700}", true) => Input::Up,
        ("\u{F701}", true) => Input::Down,
        ("\u{F702}", true) => Input::Left,
        ("\u{F703}", true) => Input::Right,
        ("\u{F748}" | "\u{1b}" | "\u{8}", true) => Input::Back,
        _ => return None,
    };
    Some(input)
}

fn image(bitmap: &Bitmap) -> slint::Image {
    slint::Image::from_rgba8(SharedPixelBuffer::clone_from_slice(
        bitmap.rgba(),
        bitmap.width(),
        bitmap.height(),
    ))
}

