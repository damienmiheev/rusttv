impl Controller {
    fn new(
        platform: Box<dyn Platform>,
        window: &HomeWindow,
        options: RunOptions,
        clock: Clock,
    ) -> Rc<RefCell<Self>> {
        let tiles = Rc::new(VecModel::default());
        window.set_tiles(ModelRc::from(tiles.clone()));
        let hidden_tiles = Rc::new(VecModel::default());
        window.set_hidden_tiles(ModelRc::from(hidden_tiles.clone()));
        let folder_tiles = Rc::new(VecModel::default());
        window.set_folder_tiles(ModelRc::from(folder_tiles.clone()));
        let menu_items = Rc::new(VecModel::default());
        window.set_menu_items(ModelRc::from(menu_items.clone()));
        let settings_sections = Rc::new(VecModel::default());
        window.set_settings_sections(ModelRc::from(settings_sections.clone()));
        let settings_rows = Rc::new(VecModel::default());
        window.set_settings_rows(ModelRc::from(settings_rows.clone()));
        let review_lines = Rc::new(VecModel::default());
        window.set_review_lines(ModelRc::from(review_lines.clone()));
        let review_code = Rc::new(VecModel::default());
        window.set_review_code(ModelRc::from(review_code.clone()));
        window.set_version(env!("CARGO_PKG_VERSION").into());
        window.set_update_status(update_line(window, &UpdateStatus::Idle));

        let (order, folders, hidden, saved_focus) =
            options
                .order_file
                .as_deref()
                .map_or_else(Default::default, |path| {
                    let loaded = order_file::load(path);
                    if let Some(warning) = loaded.warning {
                        log::warn!("{warning}");
                    }
                    (loaded.order, loaded.folders, loaded.hidden, loaded.focus)
                });
        // Focus is restored before the app list arrives, which keeps it by identity.
        let mut home = Home::new(order, folders, hidden, options.right_to_left);
        let strings = window.global::<Strings>();
        home.set_folder_names(FolderNames(Category::ALL.map(|category| {
            strings
                .invoke_folder_name(i32::try_from(category.index()).unwrap_or(i32::MAX))
                .to_string()
        })));
        if let Some(id) = &saved_focus {
            home.focus_on(id);
        }
        let controller = Rc::new_cyclic(|me| {
            RefCell::new(Self {
                home,
                platform,
                options,
                apps: HashMap::new(),
                glows: HashMap::new(),
                builtins: Builtins::new(),
                shown: Vec::new(),
                tiles,
                hidden_shown: Vec::new(),
                hidden_tiles,
                folder_shown: Vec::new(),
                folder_tiles,
                renaming: None,
                rename_timer: Timer::default(),
                menu_items,
                hero: None,
                hero_a_front: true,
                pressed: false,
                clock,
                window: window.as_weak(),
                me: me.clone(),
                tick_timer: Timer::default(),
                idle_timer: Timer::default(),
                hero_timer: Timer::default(),
                toast_timer: Timer::default(),
                marquee_timer: Timer::default(),
                marquee_for: None,
                pause_timer: Timer::default(),
                pending_artwork: VecDeque::new(),
                artwork_timer: Timer::default(),
                notices: None,
                saved_focus,
                update: UpdateStatus::Idle,
                update_timer: Timer::default(),
                settings: None,
                review: None,
                settings_status: (0, String::new()),
                hold_timer: Timer::default(),
                swallow_ok_release: false,
                pack_timer: Timer::default(),
                settings_sections,
                settings_rows,
                review_lines,
                review_code,
                remote: None,
                pairing: None,
                away: false,
            })
        });
        *controller.borrow().options.lifecycle.0.borrow_mut() = Rc::downgrade(&controller);
        settings_view::register(&controller);
        {
            let mut this = controller.borrow_mut();
            this.start_remote();
            this.reload_apps();
            this.restart_idle();
            // `render` schedules the hero after HERO_DELAY, so the first frame
            // does not wait for its backdrop; it fades in like any focus change.
            this.render();
            this.refresh_update();
        }
        controller
    }

    /// Re-reads the app list when the platform reports a change. A failed check
    /// counts as a change, so the list is never left stale. Also reads the
    /// updater's status: on Android the daily check may have just started.
    fn resume(&mut self) {
        self.away = false;
        // Phones switch back from the touchpad to the Home mirror.
        self.push_remote_view();
        self.refresh_update();
        self.pack_timer.stop();
        if let Some(history) = History::get() {
            history.resumed();
            if history.take_launcher_changed() {
                self.reload_launcher_state();
            }
        }
        let changed = self.platform.take_apps_changed().unwrap_or_else(|error| {
            log::warn!("checking for app changes failed: {error}");
            true
        });
        if changed {
            log::info!("app list changed; reloading");
            self.reload_apps();
            // Rebuild tiles and hero too: an updated app may have a new banner.
            self.shown.clear();
            self.hero = None;
            self.render();
        }
    }

    /// Re-reads the app list from the platform.
    fn reload_apps(&mut self) {
        match self.platform.list_apps() {
            Ok(entries) => {
                let apps: Vec<App> = entries.iter().map(|entry| entry.app.clone()).collect();
                self.glows.clear();
                self.apps = entries
                    .into_iter()
                    .map(|entry| (entry.app.id.clone(), AppView::new(entry)))
                    .collect();
                if self.home.set_apps(&apps) {
                    self.save_order();
                }
                // Queued again, in tile order, when the tiles are rebuilt (`render`).
                self.pending_artwork.clear();
            }
            Err(error) => {
                self.home.set_apps(&[]);
                let text = self.window.upgrade().map(|window| {
                    window
                        .global::<Strings>()
                        .invoke_couldnt_load_apps(error.to_string().into())
                });
                self.show_toast(text.unwrap_or_default());
            }
        }
    }

    /// Queues the artwork of these tiles that is still to be loaded. Only shown
    /// tiles are queued, so hidden apps cost nothing until their page opens;
    /// a folder's tile needs the first four of its apps.
    fn queue_artwork(&mut self, tiles: &[TileId]) {
        let apps = tiles.iter().flat_map(|tile| match tile {
            TileId::App(id) => std::slice::from_ref(id),
            TileId::Folder(number) => self
                .home
                .folders()
                .get(number)
                .map_or(&[][..], |folder| &folder.apps[..folder.apps.len().min(4)]),
            _ => &[],
        });
        for id in apps {
            if self.apps.get(id).is_some_and(AppView::is_pending)
                && !self.pending_artwork.contains(id)
            {
                self.pending_artwork.push_back(id.clone());
            }
        }
        self.load_artwork_later();
    }

    /// Starts loading pending artwork on a timer, so the first frame (and each
    /// key) never waits for every banner.
    fn load_artwork_later(&mut self) {
        if self.pending_artwork.is_empty() {
            self.artwork_timer.stop();
            return;
        }
        let me = self.me.clone();
        self.artwork_timer
            .start(TimerMode::Repeated, ARTWORK_TICK, move || {
                if let Some(controller) = me.upgrade() {
                    controller.borrow_mut().load_some_artwork();
                }
            });
    }

    /// Loads the next few pending artworks and shows them.
    fn load_some_artwork(&mut self) {
        let was_pending = !self.pending_artwork.is_empty();
        for _ in 0..ARTWORK_PER_TICK {
            let Some(id) = self.pending_artwork.pop_front() else {
                break;
            };
            let artwork = self.platform.artwork(&id).unwrap_or_else(|error| {
                log::warn!("loading the artwork of {id} failed: {error}");
                Artwork::Missing
            });
            let Some(app) = self.apps.get_mut(&id) else {
                continue;
            };
            app.set_artwork(&artwork);
            let tile = TileId::App(id);
            if let Some(index) = self.shown.iter().position(|shown| *shown == tile) {
                self.tiles.set_row_data(index, self.tile_data(&tile));
            }
            if let Some(index) = self.hidden_shown.iter().position(|shown| *shown == tile) {
                self.hidden_tiles.set_row_data(index, self.tile_data(&tile));
            }
            if let Some(index) = self.folder_shown.iter().position(|shown| *shown == tile) {
                self.folder_tiles.set_row_data(index, self.tile_data(&tile));
            }
            // A folder shows its first apps small.
            let folder = self.home.folders().iter().find_map(|(number, folder)| {
                folder
                    .apps
                    .iter()
                    .take(4)
                    .any(|app| matches!(&tile, TileId::App(shown) if shown == app))
                    .then_some(*number)
            });
            if let Some(folder) = folder.map(TileId::Folder)
                && let Some(index) = self.shown.iter().position(|shown| *shown == folder)
            {
                self.tiles.set_row_data(index, self.tile_data(&folder));
            }
            if self.hero.as_ref() == Some(&tile) {
                // Redraw the hero with the picture (it fades in like a tile).
                self.hero = None;
                self.show_hero();
            }
        }
        if self.pending_artwork.is_empty() {
            self.artwork_timer.stop();
            if was_pending {
                self.platform.artwork_loaded();
            }
        }
    }

    /// Handles a key from the window; returns whether it was used.
    ///
    /// A held OK repeats its key-down about every 50 ms. Those repeats are
    /// swallowed here: passed on, each restarted the long-press timer, so move
    /// mode only began on release. Held arrows keep repeating, to scroll.
    fn key(&mut self, text: &str, pressed: bool, repeat: bool) -> bool {
        let Some(input) = input_for_key(text, pressed) else {
            return false;
        };
        if !(repeat && input == Input::OkPressed) {
            self.input(input);
        }
        true
    }

    fn input(&mut self, input: Input) {
        let effect = self.home.handle(input, (self.clock)());
        if input != Input::Tick {
            self.pressed = input == Input::OkPressed
                && matches!(self.home.state(), State::Browse | State::Folder);
            self.restart_idle();
        }
        self.apply(effect);
        // Remember focus while the launcher is off screen, in case Android
        // stops it there: back on Home, focus is on the app that was opened.
        if input == Input::Paused && self.home.focused() != self.saved_focus.as_ref() {
            self.save_order();
        }
        if input == Input::Paused {
            self.close_settings_view();
            self.schedule_pack();
            self.end_rename();
        }
        if let Some(notices) = &mut self.notices {
            match input {
                Input::Up => notices.scroll_up(),
                Input::Down => notices.scroll_down(),
                _ => {}
            }
        }
        self.schedule_tick();
        // Stops polling once About closes and nothing runs.
        self.schedule_update_poll();
        self.render();
    }

    /// Carries out what the model asked for.
    fn apply(&mut self, effect: Option<Effect>) {
        match effect {
            Some(Effect::Launch(id)) => self.launch(&id),
            Some(Effect::ShowLaunchError(id)) => {
                let label = self.apps.get(&id).map_or(id.as_str(), |app| &app.label);
                let text = self
                    .window
                    .upgrade()
                    .map(|window| window.global::<Strings>().invoke_couldnt_open(label.into()));
                self.show_toast(text.unwrap_or_default());
            }
            Some(Effect::SaveOrder) => {
                self.save_order();
                // The person moved, hid or showed an app (HISTORY.md § 2).
                if let Some(history) = History::get() {
                    history.launcher_edited();
                }
            }
            Some(Effect::OpenSettings) => self.open_settings(),
            Some(Effect::Settings(input)) => self.settings_input(input),
            Some(Effect::OpenAbout) => {
                self.open_notices();
                self.refresh_update();
            }
            Some(Effect::Update) => self.update_action(),
            Some(Effect::RenameFolder(id)) => self.start_rename(id),
            // `render` fills the page and queues its artwork.
            Some(Effect::OpenHidden) | None => {}
        }
    }

    /// OK on the About page: installs the available update, else checks for
    /// one; nothing while a step runs. A failed bridge call shows as the status.
    fn update_action(&mut self) {
        let started = if self.update.is_available() {
            self.platform.install_update()
        } else if self.update.is_busy() {
            Ok(())
        } else {
            self.platform.check_for_update()
        };
        if let Err(error) = started {
            log::warn!("starting the update step failed: {error}");
            self.show_update(UpdateStatus::Failed(error.to_string()));
        }
        self.refresh_update();
    }

    /// Reads the updater's status and shows it.
    fn refresh_update(&mut self) {
        match self.platform.update_status() {
            Ok(status) => self.show_update(status),
            Err(error) => {
                log::warn!("reading the update status failed: {error}");
                self.show_update(UpdateStatus::Failed(error.to_string()));
            }
        }
        self.schedule_update_poll();
    }

    /// Pushes a changed update status to the About page's line and the About
    /// tile's dot; an unchanged one costs nothing.
    fn show_update(&mut self, status: UpdateStatus) {
        if status == self.update {
            return;
        }
        if let Some(window) = self.window.upgrade() {
            window.set_update_status(update_line(&window, &status));
            window.set_update_available(status.is_available());
        }
        self.update = status;
    }

    /// Polls the updater every [`UPDATE_POLL`] while the About page is open or
    /// an update step runs, else stops.
    fn schedule_update_poll(&mut self) {
        if self.home.state() != State::About && !self.update.is_busy() {
            self.update_timer.stop();
            return;
        }
        if self.update_timer.running() {
            return;
        }
        let me = self.me.clone();
        self.update_timer
            .start(TimerMode::Repeated, UPDATE_POLL, move || {
                if let Some(controller) = me.upgrade() {
                    controller.borrow_mut().refresh_update();
                }
            });
    }

    /// Reads the notices for the About page; a failure is shown in their place.
    fn open_notices(&mut self) {
        let text = self.platform.notices().unwrap_or_else(|error| {
            log::warn!("loading the licence notices failed: {error}");
            self.window
                .upgrade()
                .map(|window| {
                    window
                        .global::<Strings>()
                        .invoke_couldnt_load_notices(error.to_string().into())
                        .into()
                })
                .unwrap_or_default()
        });
        self.notices = Some(Notices::new(text));
    }

    /// Writes the order file with the focused tile. A failure only costs the
    /// order on the next start, so it is logged rather than shown.
    fn save_order(&mut self) {
        let Some(path) = &self.options.order_file else {
            return;
        };
        // A TV change from the history owns the order file until it ends.
        if History::get().is_some_and(History::busy) {
            return;
        }
        // Mid-move, the folders are not what the order says yet: the drop saves.
        if self.home.state() == State::Moving {
            return;
        }
        let focus = self.home.focused();
        match order_file::save(
            path,
            self.home.order(),
            self.home.folders(),
            self.home.hidden(),
            focus,
        ) {
            Ok(()) => self.saved_focus = focus.cloned(),
            Err(error) => log::warn!(
                "saving the tile order to {} failed: {error}",
                path.display()
            ),
        }
    }

    fn launch(&mut self, id: &str) {
        match self.platform.launch(id) {
            Ok(()) => {
                if let Some(delay) = self.options.simulated_pause {
                    let me = self.me.clone();
                    self.pause_timer
                        .start(TimerMode::SingleShot, delay, move || {
                            if let Some(controller) = me.upgrade() {
                                controller.borrow_mut().input(Input::Paused);
                            }
                        });
                }
            }
            Err(_) => self.input(Input::LaunchFailed),
        }
    }

    /// Sends a [`Input::Tick`] when the model's next timer can be due.
    fn schedule_tick(&mut self) {
        let delay = match self.home.state() {
            State::Browse if self.pressed => LONG_PRESS,
            State::Launching => LAUNCH_TIMEOUT,
            State::Folder if self.pressed => LONG_PRESS,
            State::Moving => self.home.folder_due().map_or(MOVE_IDLE_TIMEOUT, |due| {
                due.saturating_sub((self.clock)()).min(MOVE_IDLE_TIMEOUT)
            }),
            State::Browse
            | State::About
            | State::Menu
            | State::Hidden
            | State::Settings
            | State::Folder => {
                self.tick_timer.stop();
                return;
            }
        };
        let me = self.me.clone();
        self.tick_timer
            .start(TimerMode::SingleShot, delay, move || {
                if let Some(controller) = me.upgrade() {
                    controller.borrow_mut().input(Input::Tick);
                }
            });
    }

    /// Back to the still focus look, sway from [`SWAY_AFTER`], back to still at
    /// [`SWAY_UNTIL`]. The sway fades in and out (`home.slint`), so neither
    /// change jumps.
    fn restart_idle(&mut self) {
        self.set_idle_phase(0);
        let me = self.me.clone();
        self.idle_timer
            .start(TimerMode::SingleShot, SWAY_AFTER, move || {
                let Some(controller) = me.upgrade() else {
                    return;
                };
                let this = controller.borrow();
                this.set_idle_phase(1);
                let window = this.window.clone();
                this.idle_timer
                    .start(TimerMode::SingleShot, SWAY_UNTIL - SWAY_AFTER, move || {
                        if let Some(window) = window.upgrade() {
                            window.set_idle_phase(0);
                        }
                    });
            });
    }

    /// Starts the selected menu item's marquee from its beginning, or stops it
    /// when the menu closed. A text that fits never moves.
    fn restart_marquee(&self, window: &HomeWindow) {
        self.marquee_timer.stop();
        window.set_menu_marquee_end(false);
        if self.marquee_for.is_some() {
            self.schedule_marquee(MARQUEE_HOLD);
        }
    }

    /// After `after`, slides the selected item's text the other way, then
    /// waits for the slide plus [`MARQUEE_HOLD`] before the next one.
    fn schedule_marquee(&self, after: Duration) {
        let me = self.me.clone();
        self.marquee_timer
            .start(TimerMode::SingleShot, after, move || {
                let Some(controller) = me.upgrade() else {
                    return;
                };
                let this = controller.borrow();
                let Some(window) = this.window.upgrade() else {
                    return;
                };
                let slide = Duration::from_millis(
                    u64::try_from(window.get_menu_marquee_time()).unwrap_or_default(),
                );
                if slide.is_zero() {
                    return;
                }
                window.set_menu_marquee_end(!window.get_menu_marquee_end());
                this.schedule_marquee(slide + MARQUEE_HOLD);
            });
    }

    fn set_idle_phase(&self, phase: i32) {
        if let Some(window) = self.window.upgrade() {
            window.set_idle_phase(phase);
        }
    }

    fn show_toast(&mut self, text: SharedString) {
        if let Some(window) = self.window.upgrade() {
            window.set_toast(text);
        }
        let window = self.window.clone();
        self.toast_timer
            .start(TimerMode::SingleShot, TOAST_TIME, move || {
                if let Some(window) = window.upgrade() {
                    window.set_toast("".into());
                }
            });
    }

    /// Pushes model state to the window. Slint only redraws what actually changed.
    fn render(&mut self) {
        let Some(window) = self.window.upgrade() else {
            return;
        };
        if self.home.tiles() != self.shown {
            self.shown = self.home.tiles().to_vec();
            let rows: Vec<TileData> = self.shown.iter().map(|id| self.tile_data(id)).collect();
            self.tiles.set_vec(rows);
            self.queue_artwork(&self.shown.clone());
        }
        let hidden: Vec<TileId> = match self.home.hidden_focus() {
            Some(_) => self
                .home
                .hidden_apps()
                .iter()
                .cloned()
                .map(TileId::App)
                .collect(),
            None => Vec::new(),
        };
        if hidden != self.hidden_shown {
            self.hidden_shown = hidden;
            let rows: Vec<TileData> = self
                .hidden_shown
                .iter()
                .map(|id| self.tile_data(id))
                .collect();
            self.hidden_tiles.set_vec(rows);
            self.queue_artwork(&self.hidden_shown.clone());
        }
        if let Some(focus) = self.home.hidden_focus() {
            window.set_hidden_focus(i32::try_from(focus).unwrap_or(i32::MAX));
        }
        self.render_folder(&window);
        let (items, selected) = self.home.menu().unwrap_or_default();
        let labels: Vec<SharedString> = items
            .iter()
            .map(|item| menu_label(&window, *item))
            .collect();
        if !self.menu_items.iter().eq(labels.iter().cloned()) {
            self.menu_items.set_vec(labels);
        }
        window.set_menu_selected(i32::try_from(selected).unwrap_or(i32::MAX));
        let marquee_for = self.home.menu().map(|(_, selected)| selected);
        if marquee_for != self.marquee_for {
            self.marquee_for = marquee_for;
            self.restart_marquee(&window);
        }
        window.set_focused_index(i32::try_from(self.home.focus()).unwrap_or(i32::MAX));
        match self.home.scroll() {
            Scroll::Shelf => window.set_shelf(true),
            Scroll::Grid { first_row } => {
                window.set_shelf(false);
                window.set_first_row(i32::try_from(first_row).unwrap_or(i32::MAX));
            }
        }
        window.set_mode(if self.review.is_some() {
            7
        } else if self.pairing.is_some() {
            9
        } else {
            mode_value(self.home.state())
        });
        self.render_settings(&window);
        self.render_pairing(&window);
        window.set_pressed(self.pressed);
        if self.home.state() != State::About && self.notices.take().is_some() {
            // Closed: free the text until the page opens again.
            window.set_notices("".into());
        }
        if let Some(notices) = &self.notices {
            window.set_notices(notices.visible().into());
            window.set_notices_position(notices.position());
            window.set_notices_fraction(notices.fraction());
        }

        if self.home.focused() != self.hero.as_ref() {
            let me = self.me.clone();
            self.hero_timer
                .start(TimerMode::SingleShot, HERO_DELAY, move || {
                    if let Some(controller) = me.upgrade() {
                        controller.borrow_mut().show_hero();
                    }
                });
        }
        self.push_remote_view();
    }

    /// Starts the phone remote if a phone is paired (REMOTE.md § 3). Its
    /// events reach [`Controller::remote_event`] on the UI thread.
    fn start_remote(&mut self) {
        self.start_remote_now(self.options.remote_pairing);
        if self.options.remote_pairing
            && let Some(link) = &self.remote
        {
            let host = crate::remote::lan_address().map_or_else(
                || "<this computer's address>".to_owned(),
                |ip| ip.to_string(),
            );
            log::info!("RustTV Remote: pair at {}", link.open_pairing(&host));
        }
    }

    /// Starts the listener: with a paired phone, or when `force`d (pairing).
    fn start_remote_now(&mut self, force: bool) {
        let Some(files) = self
            .options
            .order_file
            .as_deref()
            .and_then(std::path::Path::parent)
        else {
            return;
        };
        let port = self.options.remote_port.unwrap_or(rusttv_remote::PORT);
        self.remote = crate::remote::Link::start(files, port, force, |event| {
            // Fails only once the event loop has stopped.
            let _ = slint::invoke_from_event_loop(move || {
                settings_view::with_controller(|controller| controller.remote_event(event));
            });
        });
    }

    /// Sends the phones what is on screen, when it changed.
    fn push_remote_view(&mut self) {
        if self.remote.is_none() {
            return;
        }
        let message = if self.away {
            // Phase 2 fills in the app and its text field (REMOTE.md § 5).
            TvMessage::App(PhoneAppView::default())
        } else {
            let rename = self.renaming.and(
                self.window
                    .upgrade()
                    .map(|window| window.get_rename_text().to_string()),
            );
            let view = crate::remote::home_view(
                &self.home,
                &|id| self.remote_label(id),
                self.review.is_some(),
                rename,
            );
            TvMessage::Home(view)
        };
        if let Some(link) = &mut self.remote {
            link.push(message);
        }
    }

    /// A tile's name as the phone shows it.
    fn remote_label(&self, id: &TileId) -> String {
        match id {
            TileId::App(component) => self
                .apps
                .get(component)
                .map_or_else(|| component.clone(), |app| app.label.clone()),
            TileId::Folder(number) => self
                .home
                .folders()
                .get(number)
                .map(|folder| folder.name.clone())
                .unwrap_or_default(),
            TileId::About => "About".to_owned(),
            TileId::Settings => "Settings".to_owned(),
            TileId::Hidden => "Hidden apps".to_owned(),
        }
    }

    /// Something happened on the phone remote (REMOTE.md § 4). Phone input
    /// goes through the same model calls as the remote's keys; the review
    /// screen never takes it.
    fn remote_event(&mut self, event: RemoteEvent) {
        match event {
            RemoteEvent::PairRequest {
                request,
                name,
                code,
            } => self.pair_request(request, name, code),
            RemoteEvent::Paired(_) => {
                if let Some(link) = &self.remote {
                    link.save_phones();
                }
                self.phones_changed();
                self.render();
            }
            RemoteEvent::PairingClosed => self.pairing_closed(),
            RemoteEvent::Connected(_) => {
                if let Some(link) = &mut self.remote {
                    link.resend();
                }
                if let Some(page) = &mut self.settings
                    && let Some(link) = &self.remote
                {
                    page.set_phones(link.phone_rows());
                }
            }
            // Never into the review or pairing screens; in Settings only
            // Back, so a phone can't pair, remove or approve anything.
            RemoteEvent::Input { message, .. }
                if self.review.is_none() && self.pairing.is_none() =>
            {
                let in_settings = self.home.state() == State::Settings;
                let back = matches!(
                    message,
                    PhoneMessage::Key {
                        name: PhoneKey::Back,
                        ..
                    }
                );
                if !in_settings || back {
                    self.phone_input(message);
                }
            }
            _ => {}
        }
    }

    fn phone_input(&mut self, message: PhoneMessage) {
        match message {
            PhoneMessage::Key { name, action } => {
                let input = match name {
                    PhoneKey::Up => Input::Up,
                    PhoneKey::Down => Input::Down,
                    PhoneKey::Left => Input::Left,
                    PhoneKey::Right => Input::Right,
                    PhoneKey::Back => Input::Back,
                    PhoneKey::Ok => match action {
                        KeyAction::Down => Input::OkPressed,
                        KeyAction::Up => Input::OkReleased,
                        KeyAction::Press => {
                            self.input(Input::OkPressed);
                            Input::OkReleased
                        }
                        KeyAction::Long => {
                            self.home.long_press();
                            self.restart_idle();
                            self.render();
                            return;
                        }
                    },
                    // Home, media, volume and power go to the TV's remote
                    // service in phase 2 (REMOTE.md § 5).
                    _ => return,
                };
                if name == PhoneKey::Ok || !matches!(action, KeyAction::Up | KeyAction::Long) {
                    self.input(input);
                }
            }
            PhoneMessage::Tile { id, gesture } => {
                let tile = order_file::tile_for_name(id);
                let long = gesture == Gesture::LongPress;
                let effect = self.home.point(&tile, long, (self.clock)());
                self.restart_idle();
                self.apply(effect);
                self.schedule_tick();
                self.render();
            }
            PhoneMessage::Text { edit } => self.phone_text(edit),
            PhoneMessage::Drag {
                id,
                over,
                phase,
                on,
            } => self.phone_drag(&id, over, phase, on),
            // Opening apps by name and the touchpad belong to phase 2.
            _ => {}
        }
    }

    /// Moving a tile by dragging it on the phone (REMOTE.md § 4): `over` is
    /// the tile under the finger (the dragged tile itself while nothing else
    /// is), `None` outside an open folder's panel.
    fn phone_drag(&mut self, id: &str, over: Option<String>, phase: DragPhase, on: bool) {
        let now = (self.clock)();
        let tile = order_file::tile_for_name(id.to_owned());
        let moving = self.home.state() == State::Moving;
        let over = over.map(order_file::tile_for_name);
        match phase {
            DragPhase::Start => {
                self.home.pick_up(&tile, now);
            }
            DragPhase::Move if moving => match &over {
                Some(target) if *target != tile => self.home.drag_over(target, on, now),
                Some(_) => {}
                None => self.home.drag_out(now),
            },
            // Dropped where the last move put it (the page sends every
            // change of `over` as a move first), as OK drops a moving tile.
            DragPhase::End if moving => {
                self.input(Input::OkPressed);
                self.input(Input::OkReleased);
                return;
            }
            DragPhase::Cancel if moving => {
                self.input(Input::Back);
                return;
            }
            _ => return,
        }
        self.restart_idle();
        self.schedule_tick();
        self.render();
    }

    /// Typing on the phone, into the folder name being edited.
    fn phone_text(&mut self, edit: TextEdit) {
        if self.renaming.is_none() {
            return;
        }
        let Some(window) = self.window.upgrade() else {
            return;
        };
        let mut text = window.get_rename_text().to_string();
        match edit {
            TextEdit::Insert { text: more } => text.push_str(&more),
            TextEdit::Delete { count } => {
                for _ in 0..count {
                    text.pop();
                }
            }
            TextEdit::Submit => {
                self.rename_done(&text);
                return;
            }
        }
        window.set_rename_text(text.into());
        self.render();
    }

    /// Cross-fades the hero to the focused tile.
    fn show_hero(&mut self) {
        let Some(window) = self.window.upgrade() else {
            return;
        };
        let focused = self.home.focused().cloned();
        if focused == self.hero {
            return;
        }
        let data = focused
            .as_ref()
            .map(|id| self.tile_data(id))
            .unwrap_or_default();
        let glow = match &focused {
            Some(TileId::App(component)) => self.glow(component),
            Some(builtin) => self.builtins.view(builtin).map(|view| view.glow.clone()),
            None => None,
        }
        .unwrap_or_default();
        // Fill the hidden layer, then make it the front one.
        if self.hero_a_front {
            window.set_hero_b(data);
            window.set_hero_b_glow(glow);
        } else {
            window.set_hero_a(data);
            window.set_hero_a_glow(glow);
        }
        self.hero_a_front = !self.hero_a_front;
        window.set_hero_a_front(self.hero_a_front);
        self.hero = focused;
    }

    /// The hero glow for an app; `None` if it has no artwork.
    fn glow(&mut self, component: &str) -> Option<generated::Glow> {
        if let Some(cached) = self.glows.get(component) {
            return Some(cached.clone());
        }
        let source = self.apps.get(component)?.glow_source.as_ref()?;
        let glow = hero_glow(source);
        self.glows.insert(component.to_owned(), glow.clone());
        Some(glow)
    }

    /// The open folder: its apps, focus and name, and the tile a moving app
    /// is on top of. A closed folder's apps stay in the window's model, so
    /// the panel still shows them while it shrinks away.
    fn render_folder(&mut self, window: &HomeWindow) {
        let to_i32 = |value: usize| i32::try_from(value).unwrap_or(i32::MAX);
        window.set_over_index(self.home.moving_over().map_or(-1, to_i32));
        let open = self.home.open_folder();
        window.set_folder_open(open.is_some());
        let Some(open) = open else {
            return;
        };
        let Some(folder) = self.home.folders().get(&open.id) else {
            return;
        };
        window.set_folder_name(folder.name.as_str().into());
        window.set_folder_focus(open.focus.map_or(-1, to_i32));
        let tiles: Vec<TileId> = folder.apps.iter().cloned().map(TileId::App).collect();
        if tiles != self.folder_shown {
            self.folder_shown = tiles;
            let rows: Vec<TileData> = self
                .folder_shown
                .iter()
                .map(|id| self.tile_data(id))
                .collect();
            self.folder_tiles.set_vec(rows);
            self.queue_artwork(&self.folder_shown.clone());
        }
    }

    /// OK on an open folder's name: the name field takes the keys (and on a
    /// TV, the on-screen keyboard opens).
    fn start_rename(&mut self, id: u32) {
        let Some(window) = self.window.upgrade() else {
            return;
        };
        let Some(folder) = self.home.folders().get(&id) else {
            return;
        };
        self.renaming = Some(id);
        window.set_rename_text(folder.name.as_str().into());
        window.set_renaming(true);
        window.invoke_focus_rename();
    }

    /// Enter in the name field. The TV keyboard sends its Done key before
    /// the word it is composing reaches the field, so the name is read a
    /// moment later.
    fn finish_rename_soon(&self) {
        let me = self.me.clone();
        self.rename_timer
            .start(TimerMode::SingleShot, RENAME_SETTLE, move || {
                let Some(controller) = me.upgrade() else {
                    return;
                };
                let mut this = controller.borrow_mut();
                let text = this
                    .window
                    .upgrade()
                    .map(|window| window.get_rename_text())
                    .unwrap_or_default();
                this.rename_done(&text);
            });
    }

    /// The name field was confirmed: keeps a changed name.
    fn rename_done(&mut self, text: &str) {
        if let Some(id) = self.renaming
            && self.home.rename_folder(id, text)
        {
            self.save_order();
            if let Some(history) = History::get() {
                history.launcher_edited();
            }
            // The folder's tile and the hero show its name too.
            self.shown.clear();
            self.hero = None;
        }
        self.end_rename();
        self.render();
    }

    /// Gives the keys back to the home screen.
    fn end_rename(&mut self) {
        self.rename_timer.stop();
        if self.renaming.take().is_none() {
            return;
        }
        if let Some(window) = self.window.upgrade() {
            window.set_renaming(false);
            window.invoke_focus_keys();
        }
    }

    fn tile_data(&self, id: &TileId) -> TileData {
        let component = match id {
            TileId::App(component) => component,
            TileId::Folder(number) => {
                let folder = self.home.folders().get(number);
                let minis: Vec<slint::Image> = folder
                    .into_iter()
                    .flat_map(|folder| &folder.apps)
                    .take(4)
                    .filter_map(|app| self.apps.get(app).map(|view| view.image.clone()))
                    .collect();
                return TileData {
                    label: folder
                        .map(|folder| folder.name.as_str())
                        .unwrap_or_default()
                        .into(),
                    kind: 7,
                    minis: ModelRc::new(VecModel::from(minis)),
                    ..TileData::default()
                };
            }
            TileId::About => {
                return TileData {
                    image: self.builtins.about.image.clone(),
                    kind: 3,
                    ..TileData::default()
                };
            }
            TileId::Hidden => {
                return TileData {
                    label: "Hidden apps".into(),
                    image: self.builtins.hidden.image.clone(),
                    kind: 5,
                    ..TileData::default()
                };
            }
            TileId::Settings => {
                return TileData {
                    image: self.builtins.settings.image.clone(),
                    kind: 6,
                    ..TileData::default()
                };
            }
        };
        let Some(app) = self.apps.get(component) else {
            return TileData {
                label: component.as_str().into(),
                kind: 2,
                ..TileData::default()
            };
        };
        TileData {
            label: app.label.as_str().into(),
            // A cheap handle: the tile and the hero share one image and texture.
            image: app.image.clone(),
            kind: app.kind,
            ..TileData::default()
        }
    }
}

/// What the window shows of one app, made once per app list.
///
/// The artwork's pixels are copied into one Slint image and dropped, so each
/// banner is held once (a tile and the hero share the image), plus a 48×27 copy
/// for the hero glow.
struct AppView {
    label: String,
    image: slint::Image,
    /// The `kind` of `TileData`: 0 banner, 1 icon only, 2 no artwork, 4 loading
    /// (3, 5 and 6 are the About, Hidden apps and Settings tiles).
    kind: i32,
    glow_source: Option<Bitmap>,
}

impl AppView {
    fn new(entry: AppEntry) -> Self {
        let mut view = Self {
            label: entry.app.label,
            image: slint::Image::default(),
            kind: 2,
            glow_source: None,
        };
        view.set_artwork(&entry.artwork);
        view
    }

    /// Takes the picture from `artwork`; its pixels are copied, not kept.
    fn set_artwork(&mut self, artwork: &Artwork) {
        let (image, kind, glow_source) = match artwork {
            Artwork::Banner(bitmap) => (image(bitmap), 0, Some(bitmap)),
            Artwork::Icon(bitmap) => (image(bitmap), 1, Some(bitmap)),
            Artwork::Missing => (slint::Image::default(), 2, None),
            Artwork::Later => (slint::Image::default(), 4, None),
        };
        self.image = image;
        self.kind = kind;
        self.glow_source =
            glow_source.map(|bitmap| bitmap.shrink(GLOW_SOURCE_SIZE.0, GLOW_SOURCE_SIZE.1));
    }

    /// Whether the artwork is still to be loaded ([`Artwork::Later`]).
    fn is_pending(&self) -> bool {
        self.kind == 4
    }
}

/// The banner and hero glow of one of the launcher's own tiles.
#[derive(Default)]
struct BuiltinView {
    image: slint::Image,
    glow: generated::Glow,
}

impl BuiltinView {
    /// Wraps a banner's RGBA bytes ([`BUILTIN_BANNER_SIZE`]).
    fn new(rgba: &[u8]) -> Self {
        let (width, height) = BUILTIN_BANNER_SIZE;
        // build.rs checks the size, so this is always `Some`.
        let Some(bitmap) = Bitmap::new(width, height, rgba.to_vec()) else {
            log::warn!("a built-in tile banner has the wrong size");
            return Self::default();
        };
        Self {
            image: image(&bitmap),
            glow: hero_glow(&bitmap.shrink(GLOW_SOURCE_SIZE.0, GLOW_SOURCE_SIZE.1)),
        }
    }
}

/// The About, Settings and Hidden apps tiles' banners and glows, made once.
struct Builtins {
    about: BuiltinView,
    settings: BuiltinView,
    hidden: BuiltinView,
}

impl Builtins {
    fn new() -> Self {
        Self {
            about: BuiltinView::new(ABOUT_BANNER),
            settings: BuiltinView::new(SETTINGS_BANNER),
            hidden: BuiltinView::new(HIDDEN_BANNER),
        }
    }

    /// The view of a built-in tile; `None` for an app.
    fn view(&self, id: &TileId) -> Option<&BuiltinView> {
        match id {
            TileId::About => Some(&self.about),
            TileId::Settings => Some(&self.settings),
            TileId::Hidden => Some(&self.hidden),
            TileId::App(_) | TileId::Folder(_) => None,
        }
    }
}

/// The licence notices and how far they are scrolled.
struct Notices {
    text: String,
    /// Byte offset where each line starts.
    starts: Vec<usize>,
    /// The line at the top of the panel.
    first: usize,
}

impl Notices {
    fn new(text: String) -> Self {
        let starts = std::iter::once(0)
            .chain(text.match_indices('\n').map(|(index, _)| index + 1))
            .collect();
        Self {
            text,
            starts,
            first: 0,
        }
    }

    /// The top line when the last lines are in view.
    fn last_first(&self) -> usize {
        self.starts.len().saturating_sub(NOTICES_SCREEN_LINES)
    }

    fn scroll_up(&mut self) {
        self.first = self.first.saturating_sub(NOTICES_STEP);
    }

    fn scroll_down(&mut self) {
        self.first = (self.first + NOTICES_STEP).min(self.last_first());
    }

    /// The lines from the top of the panel on, [`NOTICES_SENT_LINES`] of them.
    fn visible(&self) -> &str {
        let start = self.starts.get(self.first).copied().unwrap_or(0);
        let end = self
            .starts
            .get(self.first + NOTICES_SENT_LINES)
            .copied()
            .unwrap_or(self.text.len());
        &self.text[start..end]
    }

    /// How far down the panel is scrolled, 0..1.
    fn position(&self) -> f32 {
        match self.last_first() {
            0 => 0.0,
            last => self.first as f32 / last as f32,
        }
    }

    /// The share of all lines the panel shows, 0..1, for the scroll bar.
    fn fraction(&self) -> f32 {
        (NOTICES_SCREEN_LINES as f32 / self.starts.len() as f32).min(1.0)
    }
}

/// The value of the `Mode` global in `home.slint` for a model state.
fn mode_value(state: State) -> i32 {
    match state {
        State::Browse => 0,
        State::Moving => 1,
        State::Launching => 2,
        State::About => 3,
        State::Menu => 4,
        State::Hidden => 5,
        State::Settings => 6,
        State::Folder => 8,
    }
}

