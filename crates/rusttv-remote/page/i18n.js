  function pick(tags) {
    for (const raw of tags) {
      const tag = String(raw).toLowerCase();
      if (tag.startsWith("zh")) return /hant|-tw|-hk|-mo/.test(tag) ? "zh_TW" : "zh_CN";
      if (tag.startsWith("pt")) return "pt_BR";
      const base = tag.split("-")[0];
      if (T[base]) return base;
    }
    return "en";
  }

